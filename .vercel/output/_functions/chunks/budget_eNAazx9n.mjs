function computeBudget(doc, options = {}) {
  const days = [...doc.days].sort((a, b) => a.day - b.day);
  const workingDays = days.length;
  const asOf = options.asOf ?? todayIso();
  const budget = num(doc.zipperPlan) + num(doc.mtPlan);
  const perDayRequired = workingDays ? budget / workingDays : 0;
  let cumulative = 0;
  const rows = days.map((d) => {
    const total = num(d.zipper) + num(d.mt);
    const entered = d.zipper !== null || d.mt !== null;
    const counted2 = d.date < asOf || entered && !d.auto;
    if (counted2) cumulative += total;
    const cumTarget = perDayRequired * d.day;
    return {
      ...d,
      total,
      cumulative,
      cumTarget,
      lagging: cumTarget - cumulative,
      // J
      entered,
      counted: counted2,
      produced: counted2 && total > 0
    };
  });
  const counted = rows.filter((r) => r.counted);
  const zipperDone = counted.reduce((a, r) => a + num(r.zipper), 0);
  const mtDone = counted.reduce((a, r) => a + num(r.mt), 0);
  const totalDone = zipperDone + mtDone;
  const daysEntered = rows.filter((r) => r.produced).length;
  const daysRemaining = Math.max(workingDays - daysEntered, 0);
  const averageProduction = daysEntered ? totalDone / daysEntered : 0;
  const pending = rows.filter((r) => !r.counted && r.total > 0);
  const countedThrough = counted.length ? counted[counted.length - 1].date : null;
  return {
    rows,
    summary: {
      workingDays,
      daysEntered,
      daysRemaining,
      budget,
      perDayRequired,
      zipperPerDay: workingDays ? num(doc.zipperPlan) / workingDays : 0,
      // E8
      mtPerDay: workingDays ? num(doc.mtPlan) / workingDays : 0,
      // E10
      zipperDone,
      mtDone,
      totalDone,
      runRateRequired: daysRemaining > 0 ? (budget - totalDone) / daysRemaining : null,
      // G11
      prodDonePct: budget ? totalDone / budget : 0,
      // J5
      averageProduction,
      zipperAchievedPct: num(doc.zipperPlan) ? zipperDone / num(doc.zipperPlan) : 0,
      // J7
      mtAchievedPct: num(doc.mtPlan) ? mtDone / num(doc.mtPlan) : 0,
      // J8
      expectedMonthProduction: averageProduction * workingDays,
      // J9
      zipperRemaining: num(doc.zipperPlan) - zipperDone,
      // J10
      mtRemaining: num(doc.mtPlan) - mtDone,
      // J11
      countedThrough,
      pendingTotal: pending.reduce((a, r) => a + r.total, 0),
      pendingDate: pending.length ? pending[0].date : null
    }
  };
}
function defaultDays(month) {
  const [y, m] = month.split("-").map(Number);
  const last = new Date(Date.UTC(y, m, 0)).getUTCDate();
  const days = [];
  for (let d = 1; d <= last; d++) {
    days.push({
      day: days.length + 1,
      date: `${month}-${String(d).padStart(2, "0")}`,
      zipper: null,
      mt: null
    });
  }
  return days;
}
